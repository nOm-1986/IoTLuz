/** Celdas encendidas de un texto a escala `e`, con su origen arriba a la izquierda: [x, y, e]. */
export function celdas(texto, x, y, e = 1) {
  const out = []
  let cx = x
  for (const ch of String(texto)) {
    const g = GLIFOS[ch] ?? GLIFOS[ch.toUpperCase()] ?? DESCONOCIDO
    g.forEach((fila, fy) => {
      for (let fx = 0; fx < 5; fx++) if (fila[fx] === '1') out.push([cx + fx * e, y + fy * e, e])
    })
    cx += 6 * e
  }
  return out
}

/** Ancho en píxeles de un texto a escala `e` (sin el aire del último glifo). */
export const anchoTexto = (texto, e = 1) => [...String(texto)].length * 6 * e - e

export function icono(nombre, x, y, e = 1) {
  const out = []
  ICONOS[nombre].forEach((fila, fy) => {
    for (let fx = 0; fx < fila.length; fx++) if (fila[fx] === '1') out.push([x + fx * e, y + fy * e, e])
  })
  return out
}

/** Un solo trazado SVG para muchas celdas: miles de píxeles en un único nodo del DOM. */
export const trazado = (lista) => lista.map(([x, y, e]) => `M${x} ${y}h${e}v${e}h${-e}z`).join('')
